// Bundles Mermaid's use case parser (a hand-written Chevrotain parser, its visitor, model builder
// and DB) into tests/support/usecase-reference.mjs, the reference Pele's parser is compared with.
// Usage: node tests/support/build-usecase-reference.mjs <mermaid checkout> <directory holding the chevrotain package>
import { build } from 'esbuild';
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const root = process.argv[2];
const modules = process.argv[3];
if (!root || !modules) throw new Error('Pass the mermaid checkout and the node_modules directory that holds chevrotain.');
const outfile = process.argv[4] ?? 'tests/support/usecase-reference.mjs';
const extra = process.argv[5] ?? '';

const usecase = resolve(root, 'packages/mermaid/src/diagrams/usecase');
const tags = execFileSync('git', ['-C', root, 'tag', '--points-at', 'HEAD'], { encoding: 'utf8' }).split('\n');
const tag = tags.find((t) => t.startsWith('mermaid@')) ?? tags[0];
const chevrotain = JSON.parse(readFileSync(join(modules, 'chevrotain/package.json'), 'utf8')).version;

// Mermaid's config, sanitizer and shared accessibility store, reduced to what the use case DB reads.
const STUBS = {
  'common/commonDb.js': `
    let accTitle = '', accDescription = '', diagramTitle = '';
    export const clear = () => { accTitle = ''; accDescription = ''; diagramTitle = ''; };
    export const setAccTitle = (txt) => { accTitle = txt.replace(/^\\s+/g, ''); };
    export const getAccTitle = () => accTitle;
    export const setAccDescription = (txt) => { accDescription = txt.replace(/\\n\\s+/g, '\\n'); };
    export const getAccDescription = () => accDescription;
    export const setDiagramTitle = (txt) => { diagramTitle = txt; };
    export const getDiagramTitle = () => diagramTitle;`,
  'common/common.js': `export const sanitizeText = (text) => text;`,
  'defaultConfig.js': `export default { usecase: {} };`,
  'diagram-api/diagramAPI.js': `export const getConfig = () => ({});`,
};

const entry = `
export { usecaseLexer } from './parser/usecase.lexer.js';
export { usecaseParser } from './parser/usecase.parser.js';
export { parser } from './parser/usecase.chevrotain.js';
export { db } from './usecaseDb.js';
export { parseOrderedJsonObject, UsecaseJsonError } from './parser/usecaseJson.js';
export { getAccTitle, getAccDescription } from '../common/commonDb.js';
${extra}
`;

await build({
  stdin: { contents: entry, resolveDir: usecase, sourcefile: 'usecase-reference.ts', loader: 'ts' },
  bundle: true,
  format: 'esm',
  target: 'es2022',
  platform: 'neutral',
  mainFields: ['module', 'main'],
  nodePaths: [modules],
  outfile,
  minify: true,
  charset: 'utf8',
  legalComments: 'none',
  logLevel: 'warning',
  banner: {
    js:
      `// Generated by tests/support/build-usecase-reference.mjs; do not edit. Test-only reference parser.\n` +
      `// Mermaid ${tag}, packages/mermaid/src/diagrams/usecase. Copyright (c) 2014 - 2022 Knut Sveidqvist, MIT License.\n` +
      `// Bundles Chevrotain ${chevrotain}. Copyright (c) 2021 the original author or authors from the Chevrotain project, Apache License 2.0.\n` +
      // Chevrotain 13 calls Object.groupBy, which Node 20 lacks.
      `Object.groupBy ??= (items, key) => { const out = Object.create(null); let i = 0; for (const item of items) (out[key(item, i++)] ??= []).push(item); return out; };`,
  },
  plugins: [
    {
      name: 'mermaid-stubs',
      setup(b) {
        b.onResolve({ filter: /\.js$/ }, (args) => {
          for (const name of Object.keys(STUBS)) {
            if (args.path.endsWith('/' + name)) return { path: name, namespace: 'stub' };
          }
          return undefined;
        });
        b.onLoad({ filter: /.*/, namespace: 'stub' }, (args) => ({ contents: STUBS[args.path], loader: 'js' }));
      },
    },
  ],
});
console.log(`${outfile}: Mermaid ${tag}, Chevrotain ${chevrotain}, ${(readFileSync(outfile).length / 1024).toFixed(0)} kB`);
