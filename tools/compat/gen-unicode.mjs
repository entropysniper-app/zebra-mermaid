// Generates crates/zebra-mermaid/src/util/unicode_props.rs: the code point ranges of the
// Unicode properties that the JavaScript engine reads for `\p{L}` and `\p{N}`, so that Rust
// matches what the pinned Pele build sees in Node. Run with the Node version recorded in
// docs/research/pele-baseline.json:
//
//   node tools/compat/gen-unicode.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '../../crates/zebra-mermaid/src/util/unicode_props.rs');

function ranges(re) {
  const list = [];
  let start = -1;
  for (let c = 0; c <= 0x110000; c++) {
    const valid = c < 0x110000 && !(c >= 0xd800 && c <= 0xdfff);
    const hit = valid && re.test(String.fromCodePoint(c));
    if (hit && start < 0) start = c;
    if (!hit && start >= 0) {
      list.push([start, c - 1]);
      start = -1;
    }
  }
  return list;
}

const hex = (n) => '0x' + n.toString(16).toUpperCase();
const table = (name, list) =>
  `pub(crate) static ${name}: &[(u32, u32)] = &[\n` +
  list.map(([a, b]) => `    (${hex(a)}, ${hex(b)}),`).join('\n') +
  '\n];\n';

const text =
  `// Generated by tools/compat/gen-unicode.mjs from Node ${process.version} ` +
  `(Unicode ${process.versions.unicode}). Do not edit.\n\n` +
  table('LETTER', ranges(/\p{L}/u)) +
  '\n' +
  table('NUMBER', ranges(/\p{N}/u));
writeFileSync(out, text);
console.log('wrote', out);
